"""Dataset profiling: inventory + data quality report."""
import json
from pathlib import Path

import pandas as pd

from src.config import (CONTEXT_CSV, FLEET_CSV, RAW_DIR, RIDERS_CSV,
                        REPORTS_DIR, STATIONS_CSV, SWAP_EVENTS_CSV,
                        TICKETS_CSV)
from src.utils import get_logger

log = get_logger("profile")

SMALL_FILES = {
    "stations": STATIONS_CSV,
    "riders": RIDERS_CSV,
    "fleet_partners": FLEET_CSV,
    "support_tickets": TICKETS_CSV,
    "city_daily_context": CONTEXT_CSV,
}

DATE_COL_CANDIDATES = {"date", "event_ts", "created_ts", "signup_date",
                       "commissioned_date", "decommissioned_date",
                       "contract_start_date", "amendment_date",
                       "firmware_updated_date", "competitor_within_1_5km_since"}


def profile_small(name: str, path: Path) -> dict:
    df = pd.read_csv(path)
    info = {
        "dataset": name,
        "file": path.name,
        "rows": len(df),
        "columns": len(df.columns),
        "size_mb": round(path.stat().st_size / 1e6, 2),
    }
    return info


def profile_swap_events() -> dict:
    """Chunked profiling of the large events file."""
    info = {"dataset": "swap_events", "file": SWAP_EVENTS_CSV.name,
            "size_mb": round(SWAP_EVENTS_CSV.stat().st_size / 1e6, 2)}
    nrows = 0
    nulls = {}
    uniques = {}
    dtypes = {}
    first_ts = None
    last_ts = None
    for chunk in pd.read_csv(SWAP_EVENTS_CSV, chunksize=400_000,
                             parse_dates=["event_ts"]):
        nrows += len(chunk)
        for c in chunk.columns:
            if chunk[c].dtype == object or str(chunk[c].dtype) == "str":
                uniques.setdefault(c, set()).update(
                    chunk[c].dropna().unique().tolist()[:200])
            nulls[c] = nulls.get(c, 0) + int(chunk[c].isna().sum())
            dtypes.setdefault(c, str(chunk[c].dtype))
        ts = chunk["event_ts"]
        lo, hi = ts.min(), ts.max()
        first_ts = lo if first_ts is None or lo < first_ts else first_ts
        last_ts = hi if last_ts is None or hi > last_ts else last_ts
    info.update(rows=nrows, columns=len(dtypes), date_min=str(first_ts),
                date_max=str(last_ts), nulls=nulls, uniques={k: sorted(v) for k, v in uniques.items()})
    return info


def main() -> None:
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    rows = []
    small_profiles = {}
    for name, path in SMALL_FILES.items():
        small_profiles[name] = profile_small(name, path)
        rows.append(small_profiles[name])
    ev = profile_swap_events()
    rows.insert(0, {k: ev[k] for k in ("dataset", "file", "rows", "columns", "size_mb")})

    inv = pd.DataFrame(rows)
    inv.to_csv(REPORTS_DIR / "dataset_inventory.csv", index=False)
    log.info("wrote dataset_inventory.csv")

    # ---- data quality report ----
    lines = ["# VoltPulse AI — Data Quality Report", ""]
    lines.append(f"Generated by automated profiling of `data/raw/`.")
    lines.append("")
    lines.append("## Dataset inventory")
    lines.append("")
    try:
        tbl = inv.to_markdown(index=False)
    except Exception:
        tbl = "```\n" + inv.to_string(index=False) + "\n```"
    lines.append(tbl)
    lines.append("")

    for name, path in SMALL_FILES.items():
        df = pd.read_csv(path)
        lines.append(f"## {name} (`{path.name}`)")
        lines.append("")
        n_null = df.isna().sum()
        n_null = n_null[n_null > 0]
        if len(n_null):
            lines.append("Missing values:")
            for c, v in n_null.items():
                lines.append(f"- `{c}`: {v} ({v/len(df):.1%})")
        else:
            lines.append("No missing values.")
        dup = int(df.duplicated().sum())
        lines.append(f"- Duplicate rows: {dup}")
        lines.append("")
        # candidate key columns with high uniqueness
        for c in df.columns:
            if df[c].dtype == object and df[c].nunique() == len(df):
                lines.append(f"- Primary key candidate: `{c}` (100% unique)")
        lines.append("")

    # swap events summary
    lines.append("## swap_events (`swap_events.csv`)")
    lines.append("")
    lines.append(f"- Rows: {ev['rows']:,}")
    lines.append(f"- Columns: {ev['columns']}")
    lines.append(f"- Event timestamp range: {ev['date_min']} → {ev['date_max']}")
    lines.append("")
    lines.append("Missing values (top 10):")
    nulls = sorted(ev["nulls"].items(), key=lambda kv: -kv[1])[:10]
    for c, v in nulls:
        lines.append(f"- `{c}`: {v:,} ({v/ev['rows']:.2%})")
    lines.append("")
    lines.append("Distinct values observed (sampled per chunk):")
    for c, vals in ev["uniques"].items():
        if len(vals) <= 12:
            lines.append(f"- `{c}`: {vals}")
    lines.append("")

    report = REPORTS_DIR / "data_quality_report.md"
    report.write_text("\n".join(lines), encoding="utf-8")
    log.info("wrote data_quality_report.md")

    # dump full profile json for reference
    (REPORTS_DIR / "profile_details.json").write_text(
        json.dumps(ev, indent=2, default=str), encoding="utf-8")


if __name__ == "__main__":
    main()
